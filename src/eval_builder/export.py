"""Export ready cases to the eval tools people already use.

eval-builder is not an eval runner. It writes files for promptfoo, DeepEval and
Inspect AI (and plain JSONL) so the suite runs where your team already works.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from .draft import load_cases, load_rubric, validate
from .io import read_json, sha256_file, write_json, write_jsonl, write_yaml
from .workspace import Workspace

FORMATS = ("promptfoo", "deepeval", "inspect", "jsonl")


def _criteria_text(case: dict[str, Any], crit: dict[str, str]) -> str:
    return "\n".join(f"- {c}: {crit.get(c, '')}" for c in case.get("criteria") or [])


def _metadata(case: dict[str, Any]) -> dict[str, Any]:
    return {
        "case_id": case["id"],
        "trace_id": case.get("trace_id"),
        "tags": case.get("tags") or [],
        "criteria": case.get("criteria") or [],
    }


def _judge_summary(ws: Workspace) -> dict[str, Any] | None:
    if not ws.judge_check.exists():
        return None
    jc = read_json(ws.judge_check)
    return {
        "trustworthy": jc.get("trustworthy", []),
        "verdicts": {s["judge"]: s["verdict"] for s in jc.get("summary", [])},
        "thresholds": jc.get("thresholds"),
    }


def _export_jsonl(cases: list[dict[str, Any]], crit: dict[str, str], out: Path) -> list[Path]:
    rows = []
    for c in cases:
        rows.append(
            {
                "id": c["id"],
                "input": c.get("input"),
                "context": c.get("context") or [],
                "expected_behavior": c.get("expected_behavior"),
                "criteria": [
                    {"id": k, "description": crit.get(k, "")} for k in c.get("criteria") or []
                ],
                "reference_output": c.get("reference_output"),
                "observed_output": c.get("observed_output"),
                "metadata": _metadata(c),
            }
        )
    path = out / "cases.jsonl"
    write_jsonl(path, rows)
    return [path]


PROMPTFOO_HEADER = """Generated by eval-builder. Replace the `echo` provider with your app's
provider (https://www.promptfoo.dev/docs/providers/). `echo` only returns the prompt, so a run
with it checks the plumbing, not your app.
The prompt is the whole conversation as a JSON list of chat messages (vars.messages), which
chat providers such as openai:chat or ollama:chat accept as is. If your provider takes plain
text, use {{input}} (the latest user message) and {{context}} (the earlier turns) instead."""

PROMPTFOO_NO_GRADER = """No grader is wired in: llm-rubric uses promptfoo's default grader, which
sees only the output and the rubric. To grade with a judge you checked, give it a `provider`
in rubric.yaml (a promptfoo provider id) and export again."""

# Placeholders a rubric.yaml judge prompt may use, mapped to promptfoo test vars. In promptfoo,
# {{output}} is the output of the run being graded, not the logged one.
PROMPTFOO_PLACEHOLDERS = ("input", "context", "output", "expected_behavior", "criteria")


def promptfoo_rubric_prompt(prompt: str) -> str:
    """Turn a rubric.yaml judge prompt into a promptfoo rubricPrompt (Nunjucks).

    Known placeholders become {{var}}; everything else is wrapped in raw blocks so braces in
    the prompt (for example a JSON answer format) reach the grader unchanged.
    """
    pattern = re.compile(r"\{(" + "|".join(PROMPTFOO_PLACEHOLDERS) + r")\}")
    out: list[str] = []
    pos = 0
    for m in pattern.finditer(prompt):
        if m.start() > pos:
            out.append("{% raw %}" + prompt[pos : m.start()] + "{% endraw %}")
        out.append("{{ " + m.group(1) + " }}")
        pos = m.end()
    if pos < len(prompt):
        out.append("{% raw %}" + prompt[pos:] + "{% endraw %}")
    return "".join(out)


def _context_text(case: dict[str, Any]) -> str:
    # same rendering judge-plan uses for {context}, so a wired judge sees what it was checked on
    return (
        "\n\n".join(
            f"{m.get('role', 'user')}: {m.get('content', '')}" for m in case.get("context") or []
        )
        or "(none)"
    )


def _messages(case: dict[str, Any]) -> list[dict[str, Any]]:
    msgs = [
        {"role": m["role"], "content": m["content"]}
        for m in case.get("context") or []
        if m.get("role") in ("system", "user", "assistant")
    ]
    msgs.append({"role": "user", "content": case.get("input")})
    return msgs


def pick_grader(
    rubric: dict[str, Any],
    judges: dict[str, Any] | None,
    requested: str | None,
    target: str = "promptfoo",
) -> tuple[dict[str, Any] | None, list[str]]:
    """Choose the judge to wire into an export as its grader.

    Default: the first pointwise judge that judge-check marked trustworthy (and, for
    promptfoo, that has a `provider`). `requested` forces a judge id, with a warning when
    it did not pass.
    """
    notes: list[str] = []
    need_provider = target == "promptfoo"
    verdicts = (judges or {}).get("verdicts", {})
    by_id = {str(j.get("id")): j for j in rubric.get("judges") or []}
    if requested:
        j = by_id.get(requested)
        if j is None:
            raise ValueError(f"judge {requested!r} not in rubric.yaml; known: {sorted(by_id)}")
        if j.get("mode", "pointwise") != "pointwise":
            raise ValueError(
                f"judge {requested!r} is pairwise; the promptfoo and DeepEval graders are pointwise"
            )
        if not j.get("prompt") or (need_provider and not j.get("provider")):
            raise ValueError(
                f"judge {requested!r} needs both `prompt` and `provider` (a promptfoo provider "
                "id such as ollama:chat:qwen2.5:7b-instruct) in rubric.yaml to be wired in"
            )
        v = verdicts.get(requested, "not checked")
        if v != "trustworthy":
            notes.append(
                f"{target}: judge {requested} is wired in on request, but judge-check says: "
                f"{v}. Results graded by it inherit that"
            )
        return j, notes
    for jid in (judges or {}).get("trustworthy", []):
        j = by_id.get(jid)
        if not j or j.get("mode", "pointwise") != "pointwise" or not j.get("prompt"):
            continue
        if need_provider and not j.get("provider"):
            notes.append(
                f"judge {jid} passed judge-check but has no `provider` in rubric.yaml, so it "
                "is not wired into promptfoo; add one (for example ollama:chat:<model>)"
            )
            continue
        return j, notes
    return None, notes


def _export_promptfoo(
    cases: list[dict[str, Any]],
    crit: dict[str, str],
    suite: str,
    out: Path,
    grader: dict[str, Any] | None,
    grader_verdict: str | None,
) -> list[Path]:
    tests = []
    for c in cases:
        criteria_text = _criteria_text(c, crit)
        variables: dict[str, Any] = {
            "input": c.get("input"),
            "messages": _messages(c),
            "context": _context_text(c),
            "expected_behavior": str(c.get("expected_behavior", "")).strip(),
            "criteria": criteria_text,
        }
        rubric = f"{c.get('expected_behavior', '').strip()}\n\nCriteria:\n{criteria_text}"
        test: dict[str, Any] = {
            "description": f"{c['id']}: {str(c.get('input', ''))[:60].strip()}",
            "vars": variables,
            "assert": [{"type": "llm-rubric", "value": rubric}],
            "metadata": {
                "case_id": c["id"],
                "trace_id": c.get("trace_id"),
                "criteria": ",".join(c.get("criteria") or []),
            },
        }
        tests.append(test)
    config: dict[str, Any] = {
        "description": suite,
        "prompts": ["{{ messages | dump }}"],
        "providers": ["echo"],
    }
    header = PROMPTFOO_HEADER
    if grader is not None:
        config["defaultTest"] = {
            "options": {
                "provider": grader["provider"],
                "rubricPrompt": promptfoo_rubric_prompt(str(grader["prompt"])),
            }
        }
        header += (
            f"\nGrader: judge {grader['id']} from rubric.yaml (judge-check verdict: "
            f"{grader_verdict or 'not checked'}),\nwith its exact prompt and model. promptfoo's "
            'llm-rubric needs the grader to answer in JSON,\n{"pass": true|false, "reason": '
            '"..."}; a judge that answers with a bare word fails with\n"Could not extract JSON".'
        )
    else:
        header += "\n" + PROMPTFOO_NO_GRADER
    config["tests"] = tests
    path = out / "promptfooconfig.yaml"
    write_yaml(path, config, header)
    return [path]


DEEPEVAL_TEST = r'''"""Generated by eval-builder. Run with: deepeval test run test_eval_builder.py

Fill in `your_app` to call the system under test. Set EVAL_BUILDER_USE_OBSERVED=1 to
score the outputs that were logged instead (a regression check on past behavior).

Grader: when judge.json exists next to this file, every case is graded by that judge
from rubric.yaml (one that passed eval-builder judge-check, unless it was forced) with
its exact prompt. A judge whose provider is an Ollama model is called on the local
Ollama server (OLLAMA_HOST, default http://127.0.0.1:11434); for any other provider,
fill in `call_judge`. Without judge.json, DeepEval's GEval grades with the judge model
configured in DeepEval.
"""

import json
import os
import re
import urllib.request
from pathlib import Path

import pytest
from deepeval import assert_test
from deepeval.metrics import BaseMetric, GEval
from deepeval.test_case import LLMTestCase

try:  # DeepEval 4.x
    from deepeval.test_case import SingleTurnParams as Params
except ImportError:  # older DeepEval
    from deepeval.test_case import LLMTestCaseParams as Params

HERE = Path(__file__).parent
CASES = json.loads((HERE / "dataset.json").read_text(encoding="utf-8"))
JUDGE = (
    json.loads((HERE / "judge.json").read_text(encoding="utf-8"))
    if (HERE / "judge.json").exists()
    else None
)
POSITIVE = {"pass", "yes", "true", "good", "correct", "acceptable"}


def your_app(input: str) -> str:
    raise NotImplementedError("call the app under test here")


def call_judge(prompt: str) -> str:
    """Send the rendered judge prompt to the judge model and return its text answer."""
    provider = JUDGE.get("provider")
    pid = provider.get("id", "") if isinstance(provider, dict) else str(provider or "")
    config = provider.get("config", {}) if isinstance(provider, dict) else {}
    if pid.startswith("ollama:"):
        model = pid.split(":", 1)[1]
        for prefix in ("chat:", "completion:"):
            if model.startswith(prefix):
                model = model[len(prefix) :]
        keys = ("temperature", "top_p", "seed", "num_ctx", "num_predict")
        body = {
            "model": model,
            "prompt": prompt,
            "stream": False,
            "options": {k: config[k] for k in keys if k in config},
        }
        host = os.environ.get("OLLAMA_HOST", "http://127.0.0.1:11434")
        host = host if host.startswith("http") else "http://" + host
        req = urllib.request.Request(
            host.rstrip("/") + "/api/generate",
            json.dumps(body).encode(),
            {"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=300) as resp:
            return json.load(resp)["response"]
    raise NotImplementedError(
        f"call the judge model ({pid or JUDGE['id']}) with `prompt` here and return its answer"
    )


def parse_verdict(text: str) -> str:
    """'pass' or 'fail' (or the judge's own label) from a bare word or JSON answer."""
    t = re.sub(r"^```(?:json)?|```$", "", text.strip(), flags=re.M).strip()
    value = t
    if t.startswith("{"):
        try:
            data = json.loads(t)
            value = next((data[k] for k in ("pass", "verdict", "label") if k in data), "")
        except ValueError:
            m = re.search(r'"(?:pass|verdict|label)"\s*:\s*"?([A-Za-z]+)', t)
            value = m.group(1) if m else ""
    if isinstance(value, bool):
        return "pass" if value else "fail"
    word = str(value).strip().lower().strip(" .!\"'")
    word = word.split()[0] if word else ""
    return {"true": "pass", "false": "fail"}.get(word, word)


class CheckedJudge(BaseMetric):
    """The judge eval-builder checked, with its exact prompt from rubric.yaml."""

    def __init__(self, case: dict, threshold: float = 0.5):
        self.case = case
        self.threshold = threshold
        self.evaluation_model = JUDGE["id"]
        self.include_reason = True
        self.async_mode = False
        self.strict_mode = False

    def measure(self, test_case: LLMTestCase, *args, **kwargs) -> float:
        meta = self.case["additional_metadata"]
        fields = {
            "input": test_case.input,
            "output": test_case.actual_output or "",
            "context": meta.get("context_text") or "(none)",
            "expected_behavior": self.case.get("expected_output") or "",
            "criteria": meta.get("criteria_text") or "",
        }
        prompt = JUDGE["prompt"]
        for key, value in fields.items():
            prompt = prompt.replace("{" + key + "}", str(value))
        answer = call_judge(prompt)
        verdict = parse_verdict(answer)
        first = str((JUDGE.get("labels") or ["pass"])[0]).lower()
        self.score = 1.0 if verdict in POSITIVE or verdict == first else 0.0
        self.reason = answer.strip()
        self.success = self.score >= self.threshold
        return self.score

    async def a_measure(self, test_case: LLMTestCase, *args, **kwargs) -> float:
        return self.measure(test_case)

    def is_successful(self) -> bool:
        return bool(self.success)

    @property
    def __name__(self):
        return f"eval-builder judge {JUDGE['id']}"


def make_metric(case: dict):
    if JUDGE is not None:
        return CheckedJudge(case)
    return GEval(
        name="expected behavior",
        criteria=(
            "Judge whether the actual output does what the expected output describes. "
            "The expected output is a description of good behavior, not an exact answer. "
            + case["additional_metadata"]["criteria_text"]
        ),
        evaluation_params=[
            Params.INPUT,
            Params.ACTUAL_OUTPUT,
            Params.EXPECTED_OUTPUT,
        ],
    )


@pytest.mark.parametrize("case", CASES, ids=[c["name"] for c in CASES])
def test_case(case):
    if os.environ.get("EVAL_BUILDER_USE_OBSERVED") == "1":
        actual = case["actual_output"]
    else:
        actual = your_app(case["input"])
    test_case = LLMTestCase(
        input=case["input"],
        actual_output=actual,
        expected_output=case["expected_output"],
        context=case.get("context") or None,
    )
    assert_test(test_case, [make_metric(case)])
'''


def _export_deepeval(
    cases: list[dict[str, Any]],
    crit: dict[str, str],
    out: Path,
    judge: dict[str, Any] | None = None,
    judge_verdict: str | None = None,
) -> list[Path]:
    rows = []
    for c in cases:
        ctx = [f"{m['role']}: {m['content']}" for m in c.get("context") or []]
        rows.append(
            {
                "name": c["id"],
                "input": c.get("input"),
                "expected_output": c.get("expected_behavior"),
                "actual_output": c.get("observed_output"),
                "context": ctx or None,
                "additional_metadata": {
                    **_metadata(c),
                    "criteria_text": _criteria_text(c, crit),
                    "context_text": _context_text(c),
                },
            }
        )
    data = out / "dataset.json"
    write_json(data, rows)
    test = out / "test_eval_builder.py"
    test.write_text(DEEPEVAL_TEST, encoding="utf-8")
    files = [data, test]
    judge_file = out / "judge.json"
    if judge is not None:
        write_json(
            judge_file,
            {
                "id": judge["id"],
                "prompt": judge["prompt"],
                "provider": judge.get("provider"),
                "labels": judge.get("labels") or ["pass", "fail"],
                "judge_check_verdict": judge_verdict or "not checked",
            },
        )
        files.append(judge_file)
    elif judge_file.exists():
        judge_file.unlink()  # a judge from an earlier export no longer qualifies
    return files


INSPECT_TASK = '''"""Generated by eval-builder.

Run with: inspect eval task.py --model <provider/model>

`target` holds the expected behavior written for each case; model_graded_qa asks a
grader model whether the answer meets it.
"""

from pathlib import Path

from inspect_ai import Task, task
from inspect_ai.dataset import json_dataset
from inspect_ai.scorer import model_graded_qa
from inspect_ai.solver import generate


@task
def eval_builder_suite():
    return Task(
        dataset=json_dataset(str(Path(__file__).parent / "dataset.jsonl")),
        solver=generate(),
        scorer=model_graded_qa(),
    )
'''


def _export_inspect(cases: list[dict[str, Any]], crit: dict[str, str], out: Path) -> list[Path]:
    rows = []
    for c in cases:
        ctx = c.get("context") or []
        inp: Any = c.get("input")
        if ctx:
            inp = [
                {"role": m["role"], "content": m["content"]}
                for m in ctx
                if m.get("role") in ("system", "user", "assistant")
            ]
            inp.append({"role": "user", "content": c.get("input")})
        target = c.get("expected_behavior", "").strip()
        criteria = _criteria_text(c, crit)
        if criteria:
            target = f"{target}\n\nCriteria:\n{criteria}"
        rows.append(
            {
                "id": c["id"],
                "input": inp,
                "target": target,
                "metadata": {**_metadata(c), "observed_output": c.get("observed_output")},
            }
        )
    data = out / "dataset.jsonl"
    write_jsonl(data, rows)
    task_file = out / "task.py"
    task_file.write_text(INSPECT_TASK, encoding="utf-8")
    return [data, task_file]


def export(
    workspace: str | Path, formats: list[str] | None = None, judge: str | None = None
) -> dict[str, Any]:
    ws = Workspace.at(workspace)
    formats = formats or list(FORMATS)
    bad = [f for f in formats if f not in FORMATS]
    if bad:
        raise ValueError(f"unknown export format(s) {bad}; expected {', '.join(FORMATS)}")
    check = validate(ws.root)
    if not check["valid"]:
        return {
            "exported": False,
            "validation": check,
            "next": "fix the validation errors, then export again",
        }
    doc = load_cases(ws.root)
    rubric = load_rubric(ws.root)
    crit = {str(c["id"]): str(c.get("description", "")) for c in rubric.get("criteria") or []}
    cases = [c for c in doc.get("cases") or [] if c.get("status") == "ready"]
    suite = str(doc.get("suite", "eval-builder suite"))
    judges = _judge_summary(ws)
    verdicts = (judges or {}).get("verdicts", {})
    grader, notes = pick_grader(rubric, judges, judge) if "promptfoo" in formats else (None, [])
    grader_verdict = verdicts.get(str(grader["id"])) if grader else None
    de_judge, de_notes = (
        pick_grader(rubric, judges, judge, target="DeepEval")
        if "deepeval" in formats
        else (None, [])
    )
    notes += [n for n in de_notes if n not in notes]
    de_verdict = verdicts.get(str(de_judge["id"])) if de_judge else None
    if de_judge is not None:
        prov = de_judge.get("provider")
        pid = prov.get("id", "") if isinstance(prov, dict) else str(prov or "")
        if not pid.startswith("ollama:"):
            notes.append(
                f"DeepEval: judge {de_judge['id']} is wired in, but its provider "
                f"({pid or 'none'}) is not an Ollama model, so fill in call_judge() in "
                "test_eval_builder.py to call it"
            )
    elif "deepeval" in formats:
        notes.append(
            "DeepEval: no judge passed judge-check, so test_eval_builder.py grades with "
            "GEval and the judge model configured in DeepEval (not a judge checked here)"
        )
    if "inspect" in formats:
        notes.append(
            "Inspect AI: task.py grades with Inspect's default model_graded_qa scorer, not a "
            "judge checked here"
        )
    if grader is not None and "json" not in str(grader.get("prompt", "")).lower():
        notes.append(
            f"judge {grader['id']}'s prompt does not ask for JSON; promptfoo's llm-rubric "
            'will fail to parse a bare verdict. Have it answer {"pass": true|false, "reason": '
            '"..."} and re-run judge_plan and judge_check with that prompt'
        )
    files: list[Path] = []
    for f in formats:
        out = ws.exports / f
        out.mkdir(parents=True, exist_ok=True)
        if f == "jsonl":
            files += _export_jsonl(cases, crit, out)
        elif f == "promptfoo":
            files += _export_promptfoo(cases, crit, suite, out, grader, grader_verdict)
        elif f == "deepeval":
            files += _export_deepeval(cases, crit, out, de_judge, de_verdict)
        elif f == "inspect":
            files += _export_inspect(cases, crit, out)
    trusted_prompts = {}
    if judges:
        for j in rubric.get("judges") or []:
            if j.get("id") in judges["trustworthy"] and j.get("prompt"):
                trusted_prompts[j["id"]] = {
                    "mode": j.get("mode"),
                    "labels": j.get("labels"),
                    "prompt": j["prompt"],
                }
    manifest = {
        "cases": len(cases),
        "formats": formats,
        "files": [{"path": str(p.relative_to(ws.root)), "sha256": sha256_file(p)} for p in files],
        "judge_check": judges,
        "trusted_judge_prompts": trusted_prompts,
        "promptfoo_grader": (
            {"judge": grader["id"], "provider": grader["provider"], "verdict": grader_verdict}
            if grader
            else None
        ),
        "deepeval_grader": (
            {"judge": de_judge["id"], "provider": de_judge.get("provider"), "verdict": de_verdict}
            if de_judge
            else None
        ),
        "notes": notes,
    }
    write_json(ws.exports / "manifest.json", manifest)
    nxt = []
    if "promptfoo" in formats:
        nxt.append(
            f"promptfoo: replace the echo provider in {ws.exports / 'promptfoo'}/"
            "promptfooconfig.yaml with your app, then `npx promptfoo@latest eval`"
        )
    if "deepeval" in formats:
        nxt.append(
            "DeepEval: fill in your_app() in test_eval_builder.py (or set "
            "EVAL_BUILDER_USE_OBSERVED=1 to grade the logged outputs), then "
            "`deepeval test run test_eval_builder.py`"
        )
    if "inspect" in formats:
        nxt.append("Inspect AI: `inspect eval task.py --model <provider/model>`")
    return {"exported": True, **manifest, "next": "; ".join(nxt) or "run report"}
